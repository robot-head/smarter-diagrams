const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const browserOptions = require('./browser-options.cjs');
const checkSvg = require('./check-rendered-svg.cjs');
(async () => {
  const browser = await chromium.launch(browserOptions(process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/', true));
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
  fs.mkdirSync('artifacts', { recursive: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/');
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('revision'));
  assert.equal(await page.locator('[data-node]').count(), 4);
  const original = await page.locator('#source').inputValue();
  const box = await page.locator('[data-node="gateway"]').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 100); await page.mouse.up();
  await page.waitForFunction(() => document.querySelector('#source').value.includes('@pin'));
  await page.click('#undo'); assert.equal(await page.locator('#source').inputValue(), original);
  await page.click('#redo'); assert.match(await page.locator('#source').inputValue(), /@pin/);
  await page.click('#next'); await page.waitForFunction(() => document.querySelector('#status').textContent.includes('step 1/'));
  await page.click('#next'); await page.waitForFunction(() => document.querySelector('#status').textContent.includes('step 2/'));
  await page.click('#simulate');
  await page.waitForFunction(() => document.querySelector('#metrics').textContent.includes('saturation'));
  await page.locator('#load').fill('180'); await page.locator('#load').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#canvas [data-node="worker"]')?.dataset.saturation==='100');
  assert.match(await page.locator('#canvas [data-node="worker"] [data-simulation-overlay]').textContent(),/100% full/);
  assert.equal(await page.locator('#canvas [data-node="worker"] [data-silhouette]').evaluate(el=>getComputedStyle(el).stroke),'rgb(165, 59, 36)');
  await page.screenshot({path:'artifacts/simulation-overloaded.png',fullPage:true});
  const cut=await page.evaluate(() => {const arrow=document.querySelector('[data-arrowhead]');const id=arrow.dataset.edge;arrow.dispatchEvent(new MouseEvent('click',{bubbles:true,shiftKey:true}));return id;});
  assert.match(await page.locator('#status').textContent(), /Cut:/);
  assert(await page.locator('#canvas [data-edge]').evaluateAll((parts,id)=>parts.filter(p=>p.dataset.edge===id).every(p=>(p.dataset.arrowhead?getComputedStyle(p).fill:getComputedStyle(p).stroke)==='rgb(179, 51, 54)'),cut),'cut shafts and heads must share their state color');
  await page.click('#simulate');
  const api = await page.evaluate(async () => {
    const { WasmDocument, render_svg } = await import(new URL('./pkg/smarter_diagrams.js',location.href).href);
    const d = new WasmDocument('a\nb\n');
    d.edit(d.revision(), JSON.stringify([{ PinNode: { node: 'a', pin: { AbsoluteGrid: { x: 0, y: 0 } }, size_lock: null } }]));
    const source = d.source(); const undo = d.undo(); const restored = d.source(); d.free();
    const u=new WasmDocument('α -> β\n');u.replace_source(u.revision(),'α -> γ: λ\n');const unicode=u.source();u.free();
    return { source, undo, restored, unicode, svg: render_svg('x -> y: hello\n') };
  });
  assert.match(api.source, /@pin/); assert(api.undo); assert.equal(api.restored, 'a\nb\n'); assert.match(api.svg, /<svg/);assert.equal(api.unicode,'α -> γ: λ\n');
  assert(!api.svg.includes('<marker'), 'Wasm must use the joined arrow geometry');
  assert(api.svg.includes('data-arrowhead="end"'), 'Wasm arrowhead missing');
  for (const port of api.svg.split('<circle data-port=').slice(1)) assert(port.split('>')[0].includes('fill="transparent"'), 'Wasm port dot covers the arrow tip');
  assert.deepEqual(await page.evaluate(checkSvg,api.svg),[],'Wasm rendering geometry');
  fs.mkdirSync('artifacts', { recursive: true }); await page.screenshot({ path: 'artifacts/wasm-demo.png', fullPage: true });
  await page.goto(new URL('advanced.html', process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/').href);
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('ready'));
  const mode=await page.locator('#status').textContent();
  console.log('Stratum renderer:',mode);
  assert.equal(await page.locator('#stack [data-node]').count(),3);
  assert.equal(await page.locator('#stack [data-arrowhead="end"]').count(),3);
  assert.equal(await page.locator('#stack [data-plane-background]').count(),2);
  assert((await page.locator('#stack').textContent()).includes('RPC'));
  assert((await page.locator('#stack').textContent()).includes('runs on'));
  const stackSvg=await page.evaluate(async()=>{const {stack_json}=await import(new URL('./pkg-runtime/smarter_diagrams.js',location.href).href);return JSON.parse(stack_json(document.querySelector('#strata').value,.4)).svg;});
  assert.deepEqual(await page.evaluate(checkSvg,stackSvg),[],'spatial presentation geometry');
  assert.equal(await page.locator('#diff [data-node]').count(),4);
  await page.locator('#tilt').fill('0.7');await page.locator('#tilt').dispatchEvent('input');
  await page.locator('#morph').fill('0');await page.locator('#morph').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#diff [data-node="worker"]').getAttribute('opacity')==='0');
  assert.equal(await page.locator('#diff [data-node="worker"]').getAttribute('opacity'),'0');
  await page.locator('#morph').fill('1');await page.locator('#morph').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#diff [data-node="worker"]').getAttribute('opacity')==='1');
  assert.equal(await page.locator('#diff [data-node="worker"]').getAttribute('opacity'),'1');
  await page.screenshot({path:'artifacts/spatial-tools.png',fullPage:true});
  await page.setViewportSize({width:375,height:812});
  await page.reload();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('ready'));
  assert(await page.locator('.source-panel').evaluateAll(panels=>panels.every(panel=>!panel.open)),'mobile source panels should start collapsed');
  await page.locator('#stack-controls').getByRole('button',{name:'Fit diagram',exact:true}).click();
  assert(await page.locator('#stack .stack-stage').evaluate(stage=>stage.getBoundingClientRect().width<=stage.parentElement.clientWidth+1));
  await page.locator('#stack-controls').getByRole('button',{name:'Actual size (100%)',exact:true}).click();
  assert.equal(await page.locator('#stack-controls output').textContent(),'100%');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'spatial viewer must contain mobile overflow');
  await page.screenshot({path:'artifacts/spatial-tools-mobile.png',fullPage:true});
  await require('./visual-regression-test.cjs')(browser,page,process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/');
  await require('./node-drag-test.cjs')(browser,page,process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/');
  await require('./drag-stability-test.cjs')(browser,process.env.DIAGRAM_TEST_URL || 'http://127.0.0.1:8765/web/');
  assert.deepEqual(errors, []); console.log('Browser: Wasm geometry, pointer edits, trace playback, visible overload/cut state, semantic strata, branch morph, and mobile source/zoom controls passed.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
